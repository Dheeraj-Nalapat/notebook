#!/usr/bin/env node

/**
 * Script to automatically generate the file manifest for the static website
 * Run this script whenever you add new markdown files to Agent_Reports or Brain folders
 * 
 * Usage: node generate-manifest.js
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');

function findMarkdownFiles(dir, basePath = '') {
    const files = [];
    
    if (!fs.existsSync(dir)) {
        return files;
    }
    
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    
    for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        const relativePath = basePath ? `${basePath}/${entry.name}` : entry.name;
        
        if (entry.isDirectory()) {
            // Recursively search subdirectories
            files.push(...findMarkdownFiles(fullPath, relativePath));
        } else if (entry.isFile() && entry.name.endsWith('.md')) {
            files.push({
                name: entry.name,
                path: relativePath,
                folder: basePath
            });
        }
    }
    
    return files;
}

function generateManifest() {
    const agentReportsDir = path.join(REPO_ROOT, 'Agent_Reports');
    const brainDir = path.join(REPO_ROOT, 'Brain');
    
    const agentReports = [];
    const brain = [];
    
    // Find files in Agent_Reports
    if (fs.existsSync(agentReportsDir)) {
        const files = findMarkdownFiles(agentReportsDir, 'Agent_Reports');
        files.forEach(file => {
            // Remove 'Agent_Reports/' prefix from folder path
            const folder = file.folder.replace(/^Agent_Reports\//, '').replace(/^Agent_Reports$/, '');
            agentReports.push({
                name: file.name,
                path: file.path,
                folder: folder
            });
        });
    }
    
    // Find files in Brain
    if (fs.existsSync(brainDir)) {
        const files = findMarkdownFiles(brainDir, 'Brain');
        files.forEach(file => {
            // Remove 'Brain/' prefix and filename to get folder path
            const folderPath = file.path.replace(/^Brain\//, '').replace(/\/[^/]+\.md$/, '');
            brain.push({
                name: file.name,
                path: file.path,
                folder: folderPath
            });
        });
    }
    
    // Sort files
    agentReports.sort((a, b) => a.name.localeCompare(b.name));
    brain.sort((a, b) => {
        // Sort by folder first, then by name
        if (a.folder !== b.folder) {
            return a.folder.localeCompare(b.folder);
        }
        return a.name.localeCompare(b.name);
    });
    
    // Read the current app.js
    const appJsPath = path.join(__dirname, 'app.js');
    let appJsContent = fs.readFileSync(appJsPath, 'utf8');
    
    // Generate the new manifest section
    const manifestCode = `// File manifest - Auto-generated by generate-manifest.js
// Run 'node docs/generate-manifest.js' to regenerate this section
// Using GitHub raw content API since GitHub Pages only serves files from /docs folder
const REPO_OWNER = 'dheeraj-nalapat';
const REPO_NAME = 'notebook';
const BRANCH = 'main'; // Change this if your default branch is different (e.g., 'master')

const getRawUrl = (filePath) => {
    return \`https://raw.githubusercontent.com/\${REPO_OWNER}/\${REPO_NAME}/\${BRANCH}/\${filePath}\`;
};

// File manifest with folder structure preserved
const fileManifest = {
    agentReports: ${JSON.stringify(agentReports, null, 8)},
    brain: ${JSON.stringify(brain, null, 8)}
};`;
    
    // Find the start and end of the manifest section
    const startMarker = '// File manifest';
    
    const startIndex = appJsContent.indexOf(startMarker);
    if (startIndex === -1) {
        console.error('Could not find fileManifest section in app.js');
        process.exit(1);
    }
    
    // Find "const fileManifest = {" 
    const manifestStart = appJsContent.indexOf('const fileManifest = {', startIndex);
    if (manifestStart === -1) {
        console.error('Could not find fileManifest declaration');
        process.exit(1);
    }
    
    // Find the matching closing brace
    let braceCount = 0;
    let endIndex = manifestStart;
    let foundOpening = false;
    
    for (let i = manifestStart; i < appJsContent.length; i++) {
        if (appJsContent[i] === '{') {
            braceCount++;
            foundOpening = true;
        } else if (appJsContent[i] === '}') {
            braceCount--;
            if (foundOpening && braceCount === 0) {
                // Check if next char is semicolon
                if (appJsContent[i + 1] === ';') {
                    endIndex = i + 2;
                    break;
                }
            }
        }
    }
    
    if (endIndex === manifestStart) {
        console.error('Could not find end of fileManifest object');
        process.exit(1);
    }
    
    // Replace the manifest section
    const beforeManifest = appJsContent.substring(0, startIndex);
    const afterManifest = appJsContent.substring(endIndex);
    appJsContent = beforeManifest + manifestCode + '\n\n' + afterManifest;
    
    // Write the updated file
    fs.writeFileSync(appJsPath, appJsContent, 'utf8');
    
    console.log('✅ Manifest generated successfully!');
    console.log(`   Found ${agentReports.length} files in Agent_Reports`);
    console.log(`   Found ${brain.length} files in Brain`);
    console.log('\n   Files in Agent_Reports:');
    agentReports.forEach(f => console.log(`     - ${f.name}`));
    console.log('\n   Files in Brain:');
    brain.forEach(f => console.log(`     - ${f.folder ? f.folder + '/' : ''}${f.name}`));
}

// Run the script
try {
    generateManifest();
} catch (error) {
    console.error('Error generating manifest:', error);
    process.exit(1);
}
